RUN_PS1 = r"""# TAK relay device launcher -- generated by tools/make_relay_package.py
# Runs in the foreground with auto-restart. Normally started automatically by the
# scheduled task install.ps1 registers; .\run.ps1 by hand also works (dev/debug).
# Usage:  .\run.ps1            (reads device.env next to this script)
#         .\run.ps1 -CheckOnly (one-shot preflight: import zenoh, don't start the gateway)
param(
    [string]$Python = "python",
    [switch]$CheckOnly
)
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $here

$envFile = Join-Path $here "device.env"
if (Test-Path $envFile) {
    Get-Content $envFile | ForEach-Object {
        if ($_ -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$' -and -not $_.TrimStart().StartsWith('#')) {
            Set-Item -Path "Env:$($Matches[1])" -Value $Matches[2]
        }
    }
} else {
    Write-Host "device.env puuttuu -- paketti on rikki, luo se uudelleen make_relay_package.py:lla." -ForegroundColor Red
    exit 1
}

. (Join-Path $here "bootstrap.ps1")

if ($CheckOnly) {
    & $VenvPython -c "import zenoh, os; print('zenoh', zenoh.__version__ if hasattr(zenoh,'__version__') else '(ok)'); print('certs dir exists:', os.path.isdir('certs'))"
    exit $LASTEXITCODE
}

New-Item -ItemType Directory -Force -Path (Join-Path $here "logs") | Out-Null

while ($true) {
    $log = Join-Path $here ("logs\relay-{0}.log" -f (Get-Date -Format "yyyyMMdd"))
    Write-Host ("[{0}] kaynnistetaan tak_gateway.py, loki: {1}" -f (Get-Date -Format "HH:mm:ss"), $log)
    & $VenvPython -u (Join-Path $here "app\tak_gateway.py") 2>&1 |
        ForEach-Object { $line = "$_"; $line | Out-File -FilePath $log -Append -Encoding utf8; $line }
    Write-Host ("[{0}] relay pysahtyi (koodi {1}), uudelleenkaynnistys 10 s (Ctrl-C keskeyttaa)" -f (Get-Date -Format "HH:mm:ss"), $LASTEXITCODE) -ForegroundColor Yellow
    Start-Sleep -Seconds 10
}
"""

INSTALL_PS1 = r"""# TAK relay self-installer -- generated by tools/make_relay_package.py
# Bootstraps the venv, then registers a Scheduled Task so the relay starts
# automatically (at logon, restarted by its own loop if it crashes) and
# starts it right now. Re-running is safe: it replaces the existing task.
#
# Usage:  .\install.ps1                    (starts at YOUR logon, no admin needed)
#         .\install.ps1 -AtSystemStartup   (starts at boot before any logon; needs
#                                            admin, task runs as SYSTEM)
param(
    [string]$Python = "python",
    [switch]$AtSystemStartup
)
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $here

Write-Host "==> EFDI TAK-relay -- asennus" -ForegroundColor Cyan

# Zip-purettuja .ps1/.cmd-tiedostoja Windows saattaa merkita "internetista ladatuiksi"
# (Mark of the Web), mika estaa niiden ajon oletuksena -- poistetaan merkinta.
Get-ChildItem $here -Include *.ps1, *.cmd -Recurse | ForEach-Object {
    try { Unblock-File -Path $_.FullName -ErrorAction SilentlyContinue } catch {}
}

$envFile = Join-Path $here "device.env"
if (-not (Test-Path $envFile)) {
    Write-Host "device.env puuttuu -- paketti on rikki, luo se uudelleen make_relay_package.py:lla." -ForegroundColor Red
    exit 1
}
$system = "tak-relay"
$httpPort = "8088"
Get-Content $envFile | ForEach-Object {
    if ($_ -match '^\s*GATEWAY_SYSTEM\s*=\s*(.*?)\s*$') { $system = $Matches[1] }
    if ($_ -match '^\s*GATEWAY_HTTP_PORT\s*=\s*(.*?)\s*$') { $httpPort = $Matches[1] }
}

. (Join-Path $here "bootstrap.ps1")
Write-Host "==> Riippuvuudet kunnossa." -ForegroundColor Green

$taskName = "EFDI-TAK-Relay-$system"
$runPs1 = Join-Path $here "run.ps1"
$action = "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$runPs1`""

schtasks /Query /TN $taskName > $null 2>&1
if ($LASTEXITCODE -eq 0) {
    Write-Host "==> Poistetaan vanha ajastettu tehtava ($taskName)..." -ForegroundColor Yellow
    schtasks /Delete /TN $taskName /F > $null 2>&1
}

# Ensisijainen tapa: Task Scheduler. Osalla tileista (esim. rajoitettu paikallispolitiikka)
# schtasks /Create palauttaa "Kaytto estetty" vaikka tili omistaisi oman ONLOGON-tehtavansa
# yleensa ilman admin-oikeuksia -- silloin pudotaan Kaynnistys-kansio (shell:startup) -tapaan,
# joka toimii aina taman kayttajan omalla profiililla, ei vaadi mitaan erikoisoikeuksia.
$method = $null
if ($AtSystemStartup) {
    Write-Host "==> Rekisteroidaan tehtava: kaynnistyy laitteen kaynnistyessa (SYSTEM, vaatii admin)..." -ForegroundColor Cyan
    schtasks /Create /TN $taskName /TR $action /SC ONSTART /RU SYSTEM /RL HIGHEST /F 2>$null | Out-Null
    if ($LASTEXITCODE -eq 0) { $method = "task" }
} else {
    Write-Host "==> Rekisteroidaan tehtava: kaynnistyy omalla kirjautumisellasi..." -ForegroundColor Cyan
    schtasks /Create /TN $taskName /TR $action /SC ONLOGON /RL LIMITED /F 2>$null | Out-Null
    if ($LASTEXITCODE -eq 0) { $method = "task" }
}

$startupDir = [Environment]::GetFolderPath('Startup')
$shortcutPath = Join-Path $startupDir "$taskName.lnk"
if (-not $method) {
    if ($AtSystemStartup) {
        Write-Host "Ajastetun tehtavan luonti (ONSTART/SYSTEM) epaonnistui -- tama vaatii oikean admin-PowerShellin (Aja jarjestelmanvalvojana)." -ForegroundColor Red
        exit 1
    }
    Write-Host "==> Ajastettu tehtava ei onnistunut (kayttooikeusrajoitus talla tunnuksella) -- kaytetaan Kaynnistys-kansiota sen sijaan..." -ForegroundColor Yellow
    $wsh = New-Object -ComObject WScript.Shell
    $sc = $wsh.CreateShortcut($shortcutPath)
    $sc.TargetPath = "powershell.exe"
    $sc.Arguments = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$runPs1`""
    $sc.WorkingDirectory = $here
    $sc.WindowStyle = 7
    $sc.Save()
    $method = "startup"
    Write-Host "==> Pikakuvake luotu: $shortcutPath (kaynnistyy joka kirjautumisella, ei admin-oikeuksia)" -ForegroundColor Green
}

Write-Host "==> Kaynnistetaan relay nyt (ei tarvitse odottaa seuraavaa kirjautumista)..." -ForegroundColor Cyan
if ($method -eq "task") {
    schtasks /Run /TN $taskName | Out-Null
} else {
    Start-Process -FilePath "powershell.exe" -WorkingDirectory $here -WindowStyle Hidden `
        -ArgumentList "-NoProfile", "-ExecutionPolicy", "Bypass", "-WindowStyle", "Hidden", "-File", "`"$runPs1`""
}

Write-Host "==> Odotetaan relayn kaynnistyvan..." -ForegroundColor Cyan
Start-Sleep -Seconds 6
try {
    $status = Invoke-RestMethod -Uri "http://127.0.0.1:$httpPort/status" -TimeoutSec 5
    if ($status.healthy) {
        Write-Host "==> KAYNNISSA ja terve: http://127.0.0.1:$httpPort/status" -ForegroundColor Green
    } else {
        Write-Host ("==> Kaynnistyi mutta ei viela terve: {0}" -f ($status.reasons -join ', ')) -ForegroundColor Yellow
        Write-Host "    (tavallisin syy: NetBird-mesh ei viela yhdistetty -- tarkista 'netbird status')" -ForegroundColor Yellow
    }
} catch {
    Write-Host "==> Ei viela vastausta portista $httpPort. Voi kestaa hetken (venv/pip ensiasennus)." -ForegroundColor Yellow
    Write-Host "    Tarkista pian uudelleen: http://127.0.0.1:$httpPort/status tai logs\ -kansio." -ForegroundColor Yellow
}

Write-Host ""
Write-Host "Asennus valmis." -ForegroundColor Green
if ($method -eq "task") {
    Write-Host "Automaattikaynnistys: ajastettu tehtava ($taskName)."
} else {
    Write-Host "Automaattikaynnistys: pikakuvake Kaynnistys-kansiossa ($shortcutPath)."
}
Write-Host "run.ps1:n oma silmukka kaynnistaa relayn uudelleen jos se kaatuu tai taustaverkkoyhteys"
Write-Host "katkeaa pitkaksi aikaa -- ei tarvitse valvoa erikseen."
Write-Host "Poistaaksesi kokonaan: .\uninstall.ps1  (tai kaksoisklikkaa uninstall.cmd)"
# Asennus itsessaan onnistui tahan asti riippumatta siita jaiko $LASTEXITCODE
# ei-nollaksi jostain valivaiheen (esim. epaonnistuneen schtasks-yrityksen)
# natiivikutsusta -- asetetaan paluuarvo eksplisiittisesti niin kutsuja (esim.
# install.cmd:n virhetaso) ei tulkitse onnistunutta asennusta epaonnistuneeksi.
exit 0
"""

UNINSTALL_PS1 = r"""# Removes whatever auto-start install.ps1 registered (scheduled task or Startup
# shortcut -- it tries both, so this checks both) and stops a running relay.
# Does not delete this folder -- delete it yourself if you no longer need it.
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$system = "tak-relay"
$envFile = Join-Path $here "device.env"
if (Test-Path $envFile) {
    Get-Content $envFile | ForEach-Object {
        if ($_ -match '^\s*GATEWAY_SYSTEM\s*=\s*(.*?)\s*$') { $system = $Matches[1] }
    }
}
$taskName = "EFDI-TAK-Relay-$system"

schtasks /Query /TN $taskName > $null 2>&1
if ($LASTEXITCODE -eq 0) {
    schtasks /End /TN $taskName > $null 2>&1
    schtasks /Delete /TN $taskName /F | Out-Null
    Write-Host "Ajastettu tehtava $taskName poistettu." -ForegroundColor Green
} else {
    Write-Host "Ajastettua tehtavaa $taskName ei loytynyt." -ForegroundColor Yellow
}

$startupDir = [Environment]::GetFolderPath('Startup')
$shortcutPath = Join-Path $startupDir "$taskName.lnk"
if (Test-Path $shortcutPath) {
    Remove-Item $shortcutPath -Force
    Write-Host "Kaynnistys-kansion pikakuvake poistettu ($shortcutPath)." -ForegroundColor Green
} else {
    Write-Host "Kaynnistys-kansion pikakuvaketta ei loytynyt." -ForegroundColor Yellow
}

# Tarkeysjarjestys: run.ps1:n oma while-silmukka kaynnistaa tak_gateway.py:n uudelleen
# 10 s kuluttua jos se kuolee -- jos pysaytetaan vain python.exe, relay palaa itsestaan.
# Pysaytetaan siis ensin run.ps1:ta ajava powershell.exe, sitten python.exe-lapsiprosessi.
Get-CimInstance Win32_Process -Filter "Name='powershell.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like "*run.ps1*" -and $_.CommandLine -like "*$here*" } |
    ForEach-Object {
        Write-Host "Pysaytetaan run.ps1-silmukka (PID $($_.ProcessId))..." -ForegroundColor Yellow
        Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
    }

Get-CimInstance Win32_Process -Filter "Name='python.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like "*tak_gateway.py*" -and $_.CommandLine -like "*$here*" } |
    ForEach-Object {
        Write-Host "Pysaytetaan kaynnissa oleva relay-prosessi (PID $($_.ProcessId))..." -ForegroundColor Yellow
        Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
    }

Write-Host "Poisto valmis."
exit 0  # ei jateta edellisen native-kutsun (esim. "tehtavaa ei loytynyt") koodia paluuarvoksi
"""

