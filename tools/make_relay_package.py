#!/usr/bin/env python3
"""Build a self-contained, self-installing TAK relay device package (ZIP) for a field device.

Bundles relay/tak_gateway.py + its dependency modules, one device's mTLS cert
bundle, a native Windows self-installer (install.cmd/install.ps1 + uninstall
counterparts), and a Finnish quick-start. Drop the ZIP on a device that has a
TAK app terminal, unzip, double-click install.cmd: it bootstraps a venv,
installs eclipse-zenoh, registers automatic startup (scheduled task, or a
Startup-folder shortcut if the account can't create scheduled tasks), and
starts the relay immediately -- talking to the real EFDI backbone with CoT
going to TAK app over loopback UDP. No PowerShell window needs to stay open.

Usage:
    python tools/make_relay_package.py --system field-relay-01
    python tools/make_relay_package.py --system field-relay-01 --cert-dir certs --out dist/field-relay-01.zip

Each device gets its own package because GATEWAY_SYSTEM (used for the
heartbeat / portal display name) must be unique per device and must match
what's registered in the portal (see docs/en/field-package.md) -- register the name
before dropping the package, or the heartbeat will show up unregistered.
All devices reuse the same vendor cert (Zenoh identity is per-org, not
per-device); only GATEWAY_SYSTEM and the output ports vary.
"""
